export type Dict = Record<string, string>

export function getDict(lang: Lang): Dict {
  const base = (translations[lang] ?? translations.en) as unknown as Dict
  const defaults: Dict = {
    welcomeTitle: 'Welcome to Prose',
    welcomeContent: 'Start writing your thoughts, essays, or stories here. Prose is designed for distraction-free focus.',
    newDocTitle: 'Untitled Document',
    newFolderName: 'New Folder',
    customFontSuffix: '(Custom)',
    loading: 'Loading...',
    openSidebar: 'Open Sidebar',
    collapse: 'Collapse',
    titlePlaceholder: 'Document Title...',
    settings: 'Settings',
  }
  return new Proxy(base, {
    get(target, prop: string) {
      if (prop in target) return target[prop]
      if (prop in defaults) return defaults[prop]
      return prop
    }
  })
}

