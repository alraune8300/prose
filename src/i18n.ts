export function t(lang: Lang, key: keyof Strings): string {
  return translations[lang]?.[key] ?? translations.en[key] ?? translations.vi?.[key] ?? (key as string)
}

export type Dict = Record<string, string>

export function getDict(lang: Lang): Dict {
  const langDict = ((translations[lang] || {}) as unknown) as Record<string, string>
  const enDict = ((translations.en || {}) as unknown) as Record<string, string>
  const viDict = ((translations.vi || {}) as unknown) as Record<string, string>
  const defaults: Dict = {
    welcomeContent: 'Start writing your thoughts, essays, or stories here. Prose is designed for distraction-free focus.',
    newDocTitle: 'Untitled Document',
    newFolderName: 'New Folder',
    customFontSuffix: '(Custom)',
    loading: 'Loading...',
    titlePlaceholder: 'Document Title...',
  }
  return new Proxy((langDict || {}) as Dict, {
    get(target, prop: string) {
      if (typeof prop !== 'string') return undefined
      if (prop in target && target[prop] !== undefined && target[prop] !== '') {
        return target[prop]
      }
      if (prop in enDict && enDict[prop] !== undefined && enDict[prop] !== '') {
        return enDict[prop]
      }
      if (prop in viDict && viDict[prop] !== undefined && viDict[prop] !== '') {
        return viDict[prop]
      }
      if (prop in defaults) {
        return defaults[prop]
      }
      return prop
    }
  })
}

